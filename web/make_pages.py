"""Writes site/zh/index.html from site/index.html (the English source).

The Chinese page is a real static page at /zh/ with Chinese text, title and
description, so search engines index each language separately. It shares
the code and art through <base href="../">.

    python3 make_pages.py
"""
import re
from pathlib import Path

site = Path(__file__).parent / "site"
html = (site / "index.html").read_text(encoding="utf-8")

TEXT = {
    "loading": "加载中…",
    "tear": "按住包装顶部横向拖动撕开，或直接点一下。",
    "again": "再开一包",
    "claim": "抽卡系统由 Rust 构建 · 代码仅 66 KB <small>（WebAssembly + JS，gzip 压缩后）</small>",
    "eyebrow": "两张图，一个活起来的镜头",
    "title": "雨夜港口的巨型机甲，用 Rust 让它活起来",
    "body": "雨、来回扫的探照灯、闪电、从装甲上倾泻的水流和待机呼吸，全部由 Rust + WebAssembly 用 WebGL2 实时绘制。每一帧都是时间的函数，所以同一份代码也能直接录成视频。代码仅 32 KB。",
    "note": "机甲和港口的原图来自生图软件，动作、光线和天气都是代码。",
    "how": "看看是怎么做的 →",
}
SWAPS = [
    ('<html lang="en">', '<html lang="zh-CN">'),
    ('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="../">'),
    ("<title>Playmand · A card pack built in Rust</title>", "<title>Playmand · 用 Rust 构建的抽卡系统</title>"),
    ('<meta name="description" content="A tearable foil card pack and five holographic cards, written in Rust and compiled to WebAssembly with WebGL2. 66 KB of code. Made with the Playmand skill.">',
     '<meta name="description" content="可撕开的铝箔卡包和五张全息卡片，用 Rust 编写、编译为 WebAssembly，以 WebGL2 绘制，代码仅 66 KB。由 Playmand 技能制作。">'),
    ('<link rel="canonical" href="https://playmand.com/">', '<link rel="canonical" href="https://playmand.com/zh/">'),
    ('<meta property="og:title" content="Playmand · A card pack built in Rust">', '<meta property="og:title" content="Playmand · 用 Rust 构建的抽卡系统">'),
    ('<meta property="og:description" content="Tear a foil pack and five holographic cards turn face up. Built in Rust and WebAssembly, 66 KB of code.">',
     '<meta property="og:description" content="撕开铝箔卡包，五张全息卡片依次翻面。Rust + WebAssembly 构建，代码仅 66 KB。">'),
    ('<span id="langLabel">EN</span>', '<span id="langLabel">中文</span>'),
    ('<a href="./" lang="en" hreflang="en" aria-current="true">English</a><a href="zh/" lang="zh-CN" hreflang="zh-CN">简体中文</a>',
     '<a href="./" lang="en" hreflang="en">English</a><a href="zh/" lang="zh-CN" hreflang="zh-CN" aria-current="true">简体中文</a>'),
    ('aria-label="Card pack"', 'aria-label="卡包"'),
    ('aria-label="Next"', 'aria-label="下一屏"'),
    ('aria-label="A giant mecha standing in a rainy night harbour"', 'aria-label="雨夜港口里的一台巨型机甲"'),
    ('href="https://github.com/edison7009/Playmand/blob/main/skills/playmand/references/art-direction.md"',
     'href="https://github.com/edison7009/Playmand/blob/main/docs/zh-CN/playmand/references/art-direction.md"'),
]
for old, new in SWAPS:
    assert old in html, old
    html = html.replace(old, new, 1)
for key, text in TEXT.items():
    html, n = re.subn(rf'(data-t="{key}"[^>]*>)(.*?)(</span>|</button>|</div>|</h2>|</p>|</a>)', rf"\g<1>{text}\g<3>", html, count=1)
    assert n == 1, key
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by web/make_pages.py from site/index.html; edit that file instead. -->", 1)
(site / "zh").mkdir(exist_ok=True)
(site / "zh" / "index.html").write_text(html, encoding="utf-8")
print("wrote", site / "zh" / "index.html")
