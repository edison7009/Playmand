"""Sample particle targets from two rasterized icons for the `icons` demo.

python demos/sample_icons.py <claude.png> <chatgpt.png> [--count 3200]

Each PNG is a dark or coloured shape on a white background (any size).
Points are sampled uniformly inside the shape with a fixed seed, centred,
scaled to fit a 300 px box (y up), and written to demos/src/icon_points.rs.
Requires Pillow.
"""

import argparse
import random
from pathlib import Path

from PIL import Image

BOX = 300.0


def sample(path, count, seed):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = im.load()
    inside = [(x, y) for y in range(0, h, 2) for x in range(0, w, 2) if sum(px[x, y]) < 600]
    xs = [p[0] for p in inside]
    ys = [p[1] for p in inside]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    scale = BOX / max(max(xs) - min(xs), max(ys) - min(ys))
    rng = random.Random(seed)
    picks = rng.sample(inside, min(count, len(inside)))
    return [((x + rng.random() * 2 - cx) * scale, (cy - y - rng.random() * 2) * scale) for x, y in picks]


def rust_array(name, pts):
    body = ",".join(f"[{x:.1f},{y:.1f}]" for x, y in pts)
    return f"pub const {name}: &[[f32; 2]] = &[{body}];\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("claude")
    ap.add_argument("chatgpt")
    ap.add_argument("--count", type=int, default=3200)
    args = ap.parse_args()
    out = Path(__file__).resolve().parent / "src" / "icon_points.rs"
    out.write_text(
        "//! Generated by demos/sample_icons.py. Particle targets for the icons demo.\n\n"
        + rust_array("CLAUDE", sample(args.claude, args.count, 1))
        + rust_array("CHATGPT", sample(args.chatgpt, args.count, 2)),
        encoding="utf-8",
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
